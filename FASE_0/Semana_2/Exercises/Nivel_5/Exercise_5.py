#Prueba 0.1 + 0.2 y explica por qué no da 0.3.

Number_1 = 0.1
Number_2 = 0.2
result = Number_1 + Number_2
print(result)

#El resultado de la suma de 0.1 y 0.2 no es exactamente 0.3 debido a la forma en que los números de punto flotante se representan en la memoria de la computadora. Los números decimales como 0.1 y 0.2 no se pueden representar con precisión en binario, lo que lleva a pequeñas imprecisiones en los cálculos. Por lo tanto, el resultado de la suma puede ser ligeramente diferente de 0.3, como 0.30000000000000004.